-- 05_submissions_grades.sql
-- Run Users.sql, 02_students_faculty.sql, 03_courses_enrollments.sql and 04_assignments.sql before this file.
-- Submissions exist only for students enrolled in the assignment's course.
-- About 8% of possible submissions are missing (not submitted) and about 10% of submissions are ungraded.
-- All submissions are on or before the assignment due date.
-- Letter grades: A >= 90%, B >= 75%, C >= 60%, D >= 40%, F < 40% of max_marks.

PRAGMA foreign_keys = ON;
BEGIN TRANSACTION;

CREATE TABLE IF NOT EXISTS submissions (
    id INTEGER PRIMARY KEY,
    assignment_id INTEGER NOT NULL,
    student_id INTEGER NOT NULL,
    submitted_date TEXT NOT NULL,
    UNIQUE (assignment_id, student_id),
    FOREIGN KEY (assignment_id) REFERENCES assignments(id),
    FOREIGN KEY (student_id) REFERENCES students(id)
);

CREATE TABLE IF NOT EXISTS grades (
    id INTEGER PRIMARY KEY,
    submission_id INTEGER NOT NULL UNIQUE,
    marks REAL NOT NULL CHECK (marks >= 0),
    letter_grade TEXT CHECK (letter_grade IN ('A','B','C','D','F')),
    remarks TEXT,
    FOREIGN KEY (submission_id) REFERENCES submissions(id)
);

-- A student may only submit to assignments of courses they are enrolled in.
CREATE TRIGGER IF NOT EXISTS trg_submission_enrolled
BEFORE INSERT ON submissions
WHEN NOT EXISTS (
    SELECT 1 FROM enrollments e
    JOIN assignments a ON a.course_id = e.course_id
    WHERE a.id = NEW.assignment_id AND e.student_id = NEW.student_id
)
BEGIN
    SELECT RAISE(ABORT, 'Student is not enrolled in the course for this assignment');
END;

-- Marks cannot exceed the assignment's max_marks.
CREATE TRIGGER IF NOT EXISTS trg_grade_max_marks
BEFORE INSERT ON grades
WHEN NEW.marks > (
    SELECT a.max_marks FROM submissions s
    JOIN assignments a ON a.id = s.assignment_id
    WHERE s.id = NEW.submission_id
)
BEGIN
    SELECT RAISE(ABORT, 'Marks exceed max_marks for this assignment');
END;

