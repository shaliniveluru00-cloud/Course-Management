-- 06_previous_courses.sql
-- Run Users.sql and 02_students_faculty.sql before this file.
-- Courses each student took in an earlier year, with grade, attendance and result.
-- Every student gets the 6 courses of their own department. Each course is taught by
-- a faculty member of the same department (faculty_id matches the supplied faculty table).
-- Grades and attendance are random (fixed seed, so this file is always the same).
--
-- Rules:
--   attendance below 60%  -> grade DX (debarred for shortage of attendance), status Failed
--   attendance 60%+ and grade F -> status Failed
--   anything else               -> status Completed

PRAGMA foreign_keys = ON;
BEGIN TRANSACTION;

CREATE TABLE IF NOT EXISTS previous_courses (
    id INTEGER PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    credits INTEGER NOT NULL CHECK (credits > 0),
    faculty_id INTEGER NOT NULL,
    FOREIGN KEY (faculty_id) REFERENCES faculty(id)
);

CREATE TABLE IF NOT EXISTS previous_enrollments (
    id INTEGER PRIMARY KEY,
    student_id INTEGER NOT NULL,
    course_id INTEGER NOT NULL,
    grade TEXT NOT NULL CHECK (grade IN ('A','B','C','D','F','DX')),
    classes_held INTEGER NOT NULL CHECK (classes_held > 0),
    classes_attended INTEGER NOT NULL CHECK (classes_attended >= 0 AND classes_attended <= classes_held),
    status TEXT NOT NULL CHECK (status IN ('Completed','Failed')),
    UNIQUE (student_id, course_id),
    FOREIGN KEY (student_id) REFERENCES students(id),
    FOREIGN KEY (course_id) REFERENCES previous_courses(id)
);

